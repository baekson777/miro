// Phase-1 export: generate frozen maze JSON + embedded Dart snapshots.
// Run: flutter test tool/export_fixed_mazes_test.dart
// Does not modify GameController / GameMode / leaderboard.

import 'dart:convert';
import 'dart:io';

import 'package:blind_weekly_maze/features/maze/data/dfs_maze_generator.dart';
import 'package:blind_weekly_maze/features/maze/data/fixed_maze_path.dart';
import 'package:blind_weekly_maze/features/maze/domain/fixed_maze_definition.dart';
import 'package:blind_weekly_maze/features/maze/domain/maze_cell.dart';
import 'package:flutter_test/flutter_test.dart';

final class _Spec {
  const _Spec({
    required this.mazeId,
    required this.difficulty,
    required this.size,
    required this.seed,
    required this.start,
    required this.exit,
    required this.expectedShortest,
    required this.fileStem,
  });

  final String mazeId;
  final String difficulty;
  final int size;
  final int seed;
  final GridPos start;
  final GridPos exit;
  final int expectedShortest;
  final String fileStem;
}

const specs = <_Spec>[
  _Spec(
    mazeId: 'VERY_EASY-001',
    difficulty: 'veryEasy',
    size: 11,
    seed: 505,
    start: GridPos(0, 0),
    exit: GridPos(10, 10),
    expectedShortest: 22,
    fileStem: 'very_easy_001',
  ),
  _Spec(
    mazeId: 'EASY-001',
    difficulty: 'easy',
    size: 15,
    seed: 1009,
    start: GridPos(0, 0),
    exit: GridPos(14, 14),
    expectedShortest: 30,
    fileStem: 'easy_001',
  ),
  _Spec(
    mazeId: 'NORMAL-001',
    difficulty: 'normal',
    size: 21,
    seed: 2013,
    start: GridPos(0, 0),
    exit: GridPos(20, 20),
    expectedShortest: 44,
    fileStem: 'normal_001',
  ),
  _Spec(
    mazeId: 'HARD-001',
    difficulty: 'hard',
    size: 27,
    seed: 3045,
    start: GridPos(0, 0),
    exit: GridPos(26, 19),
    expectedShortest: 59,
    fileStem: 'hard_001',
  ),
  _Spec(
    mazeId: 'VERY_HARD-001',
    difficulty: 'veryHard',
    size: 33,
    seed: 4006,
    start: GridPos(0, 0),
    exit: GridPos(32, 32),
    expectedShortest: 80,
    fileStem: 'very_hard_001',
  ),
];

void main() {
  test('export fixed maze snapshots and verify round-trip', () {
    const gen = DfsMazeGenerator();
    final outDir = Directory('lib/features/maze/data/fixed_mazes');
    if (!outDir.existsSync()) {
      outDir.createSync(recursive: true);
    }

    final snapshotEntries = <String, String>{};
    final checksums = <String, String>{};

    for (final spec in specs) {
      final maze = gen.generate(size: spec.size, seed: spec.seed);

      expect(maze.start, spec.start, reason: spec.mazeId);
      expect(maze.exit, spec.exit, reason: spec.mazeId);

      final def = FixedMazeDefinition.fromMazeGrid(
        maze: maze,
        mazeId: spec.mazeId,
        difficulty: spec.difficulty,
      );

      expect(def.checksumValid, isTrue, reason: '${spec.mazeId} checksum');
      expect(def.seedUsed, spec.seed);
      expect(def.generatorVersion,
          FixedMazeDefinition.generatorVersionGrowingTreeV1);
      expect(def.rulesVersion, FixedMazeDefinition.rulesVersionV1);

      // Round-trip via JSON string (key order from toJson — payload checksum
      // is independent of JSON key order).
      final jsonStr = const JsonEncoder.withIndent('  ').convert(def.toJson());
      final reloaded = FixedMazeDefinition.fromJsonString(
        jsonEncode(def.toJson()), // compact parse path
      );
      expect(reloaded.checksum, def.checksum);
      expect(reloaded.checksumValid, isTrue);
      expect(reloaded.wallsEqualToGrid(maze), isTrue,
          reason: '${spec.mazeId} walls vs original');

      final gridFromSnap = reloaded.toMazeGrid();
      expect(reloaded.wallsEqualToGrid(gridFromSnap), isTrue);

      final shortest = FixedMazePath.shortestLength(gridFromSnap);
      expect(shortest, spec.expectedShortest,
          reason: '${spec.mazeId} shortest path');

      final jsonPath = '${outDir.path}/${spec.fileStem}.json';
      File(jsonPath).writeAsStringSync('$jsonStr\n');
      snapshotEntries[spec.mazeId] = jsonEncode(def.toJson());
      checksums[spec.mazeId] = def.checksum;

      // ignore: avoid_print
      print('${spec.mazeId}: checksum=${def.checksum} '
          'shortest=$shortest file=$jsonPath');
    }

    // Embedded Dart snapshots for asset-free loading.
    final dartBuf = StringBuffer()
      ..writeln('// GENERATED by tool/export_fixed_mazes_test.dart — do not edit by hand.')
      ..writeln('// ignore_for_file: lines_longer_than_80_chars')
      ..writeln()
      ..writeln('/// Compact JSON strings for frozen ranked mazes.')
      ..writeln('abstract final class FixedMazeSnapshots {')
      ..writeln('  static const Map<String, String> byMazeId = {');
    for (final e in snapshotEntries.entries) {
      final escaped = e.value.replaceAll(r'$', r'\$');
      dartBuf.writeln("    '${e.key}': r'''$escaped''',");
    }
    dartBuf
      ..writeln('  };')
      ..writeln()
      ..writeln('  static String? jsonFor(String mazeId) => byMazeId[mazeId];')
      ..writeln('}');

    final dartPath =
        'lib/features/maze/data/fixed_mazes/fixed_maze_snapshots.dart';
    File(dartPath).writeAsStringSync(dartBuf.toString());
    // ignore: avoid_print
    print('Wrote $dartPath');
    // ignore: avoid_print
    print('Checksums: $checksums');
  });
}
